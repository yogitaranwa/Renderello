"""Empty-scene prompt construction for the background-only generation route.

The scene model receives ONLY the environment. The product is never named,
described or implied anywhere in the prompt: a prompt that describes the
product for a paragraph and then appends "no product" is contradictory, and
models follow the dominant description - that is the measured 20 Nov 2026
duplicate-product failure (a hallucinated second bottle behind the preserved
cutout).

Detailed prompts are kept LONG by design: length is not the defect,
contradiction is. All the detail describes the
empty set - surface, wall, horizon, lighting, camera, material treatment,
mood and the unobstructed placement area. Product-fidelity instructions live
in the separate product-edit prompts (whole/hybrid routes), never here.
"""

# Hard exclusion block, grounded in the archived 13 Nov 2026 empty-scene
# request (scoped/scripts/Renderello-MagicHour-empty-scene-pipeline-2146.py),
# generalized beyond one product type.
_EXCLUSIONS = (
    "Completely empty set: no product, no bottle, no packaging, no pedestal, "
    "no platform, no plinth, no riser, no props, no merchandise, no text, no "
    "logo, no label, no object silhouette, and no cast shadow from an absent "
    "object. Do not render any object. The placement area stays completely "
    "unobstructed for later photographic placement of the real item. "
    "All illumination comes from outside the photograph. Keep every light, "
    "softbox, reflector, fill card, stand, tripod, camera and lighting rig "
    "entirely outside the frame, including the image edges. Show only the "
    "finished empty environment, never the equipment used to illuminate it."
)

_ASPECT_WORDS = {
    "1:1": "Square commercial photograph",
    "4:5": "Vertical 4:5 commercial photograph",
    "3:4": "Vertical 3:4 commercial photograph",
    "16:9": "Wide 16:9 commercial photograph",
    "3:2": "Wide 3:2 commercial photograph",
    "9:16": "Tall 9:16 commercial photograph",
}


class UnsupportedEmptySceneStaging(ValueError):
    """This source-locked compositor cannot execute the requested staging."""


# These fragments describe the EMPTY environment, never an absent foreground.
# Full/native editor prompts still use the unchanged TemplateSpec fields.
_EMPTY_FIELDS = {
    "clean_studio": ("continuous white seamless studio sweep with a bare level floor",
        "broad diffuse illumination from front-left with gentle right-side fill, neutral 5500K",
        "85mm lens, level eye-height view, unobstructed central floor area", "clinical neutral catalog finish"),
    "lifestyle_kitchen": ("bare light oak countertop, softly blurred bright kitchen interior in the distance",
        "warm diffuse rear-left window illumination with gentle frontal fill, 4800K",
        "50mm lens at counter height, distant shallow-depth background, central countertop unobstructed", "warm morning interior"),
    "natural_outdoor": ("bare weathered stone or wood surface, softly blurred distant green foliage",
        "open-shade daylight, subtle distant dappled illumination, gentle sky fill, 5600K",
        "60mm lens at surface level, low distant horizon, central surface clear", "fresh muted organic finish"),
    "seasonal_holiday": ("bare continuous tabletop, distant pine foliage and warm bokeh at far frame edges only",
        "warm diffuse 3800K illumination with cooler edge separation and distant sparkle",
        "70mm lens, slightly elevated 15-degree view, wide clear foreground placement area", "restrained premium festive atmosphere"),

}
_UNSUPPORTED_STAGING = {
    "luxury_hero": "polished reflective staging requires source-consistent foreground reflections",
    "flat_lay": "overhead staging requires the dedicated flatlay conditioning route, not the floor-wall guide",
    "editorial_beauty": "raised pedestal contact/occlusion needs a reviewed target-surface layout",
    "minimal_tabletop": "raised podium contact/occlusion needs a reviewed target-surface layout",
    "social_ad": "suspended or tilted staging needs a source-compatible placement route",
    "reflective_surface": "a source-consistent reflected foreground is not generated by empty-scene compositing",
}


def _environment_fields(template, reviewed_source_view=None):
    import re
    key = getattr(template, "key", None)
    if key == "flat_lay" and reviewed_source_view == "overhead":
        return ("one continuous horizontal linen or paper surface, bare center and clear margins",
                "broad diffuse overhead illumination, even 5500K neutral light",
                "true overhead 90-degree view, no wall, no horizon, no raised staging",
                "tidy graphic editorial finish")
    if key in _UNSUPPORTED_STAGING:
        raise UnsupportedEmptySceneStaging("empty-scene staging unsupported for " + key + ": " + _UNSUPPORTED_STAGING[key])
    if key in _EMPTY_FIELDS:
        from .templates import TEMPLATES
        if template != TEMPLATES[key]:
            raise ValueError("modified template requires explicit empty-scene fields")
        return _EMPTY_FIELDS[key]
    fields = tuple(getattr(template, name, "") or fallback for name, fallback in (
        ("scene", "bare seamless studio sweep"),
        ("lighting", "soft diffuse illumination from outside the frame"),
        ("camera", "level straight-on view of an empty central surface"),
        ("mood", "calm commercial finish")))
    for field in fields:
        if re.search(r"\b(product|bottle|packaging|label|logo|softbox|reflector|tripod|pedestal|plinth|podium)\b|fill card|light stand|lighting rig", field, re.I):
            raise ValueError("positive empty-scene field names a product, equipment or unsupported staging")
    return fields


class EmptyScenePrompt(str):
    def __new__(cls, value, *, staging="floor_wall", reviewed_source_view=None, reviewed_alpha_sha256=None):
        obj = super().__new__(cls, value)
        obj.staging = staging
        obj.reviewed_source_view = reviewed_source_view
        obj.reviewed_alpha_sha256 = reviewed_alpha_sha256
        return obj

    """Marker type: composite_with_scene(conditioning=\"empty_guide\") only
    accepts this, so a hand-written product-bearing prompt with a \"no
    product\" tail (the 20 Nov 2026 failure shape) can never reach the
    scene model through that path."""


def build_empty_scene_prompt(template, *, aspect_key: str = "1:1",
                             horizon_frac: float = 0.60,
                             instruction: str = "",
                             reviewed_source_view: str | None = None,
                             reviewed_alpha_sha256: str | None = None) -> str:
    """Environment-only scene prompt from a template's declared set design.

    template carries scene/lighting/camera/mood text (TemplateSpec fields).
    horizon_frac is the floor-wall division as a fraction of image height,
    matched to the two-tone conditioning guide the model also receives.
    instruction is the user's environment note; it is included only after
    product-naming terms are refused, keeping the prompt non-contradictory.
    """
    if not 0.3 <= horizon_frac <= 0.8:
        raise ValueError("horizon fraction outside the usable set range")
    scene, lighting, camera, mood = _environment_fields(template, reviewed_source_view)
    if getattr(template, "key", None) == "flat_lay":
        import re
        if not isinstance(reviewed_alpha_sha256, str) or not re.fullmatch(r"[0-9a-f]{64}", reviewed_alpha_sha256):
            raise ValueError("overhead requires a pixel-reviewed complete native alpha bound by SHA256; exact RGB does not prove a complete product")
    overhead = getattr(template, "key", None) == "flat_lay"
    opener = _ASPECT_WORDS.get(aspect_key, "Commercial photograph")
    pct = round(horizon_frac * 100)
    parts = [
        f"{opener} of a completely EMPTY premium product-photography set.",
        ("The supplied uniform guide is a continuous horizontal surface seen from directly above; no wall or horizon." if overhead else
         "The supplied two-tone guide only indicates the floor-wall division; it is not an object and nothing sits on the surface."),
        f"Set: {scene}.",
        ("The continuous horizontal surface fills every edge of the image; the whole frame remains clear." if overhead else
         f"The floor-wall junction sits at approximately {pct} percent of image height, with the support surface continuous, level and uninterrupted across the full foreground."),
        f"Lighting: {lighting}.",
        f"Camera: {camera}.",
        f"Finish: {mood}.",
        (_EXCLUSIONS.replace("Completely empty set:", "Completely empty foreground:").replace("no props, ", "").replace("no object silhouette", "no foreground object silhouette").replace("Do not render any object.", "Do not render any foreground object.") + " Any seasonal decoration stays distant at the far frame edges; the central placement area and all foreground remain bare."
         if getattr(template, "key", None) == "seasonal_holiday" else _EXCLUSIONS),
    ]
    note = (instruction or "").strip()
    if note:
        lowered = note.lower()
        for term in ("product", "bottle", "label", "logo", "packag",
                     "jar", "tube", "box", "cream", "perfume", "spray",
                     "reflector", "fill card", "light stand", "tripod",
                     "lighting rig", "camera in frame"):
            if term in lowered:
                raise ValueError(
                    "environment instruction names the product or in-frame equipment; "
                    "keep both out of the empty-scene prompt")
        parts.append(f"Additional environment-only note: {note}.")
    return EmptyScenePrompt(" ".join(parts), staging="overhead" if overhead else "floor_wall",
                            reviewed_source_view=reviewed_source_view, reviewed_alpha_sha256=reviewed_alpha_sha256)
